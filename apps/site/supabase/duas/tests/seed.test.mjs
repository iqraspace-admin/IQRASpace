import test, { before } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { bootDb, as } from './helpers.mjs';
import { here, normalizeArabic as nz } from '../lib.mjs';

const canonical = JSON.parse(readFileSync(join(here, 'data', 'canonical_duas.json'), 'utf8'));
const bundled = JSON.parse(readFileSync(join(here, 'data', 'bundled_snapshot.json'), 'utf8'));
const legacy = JSON.parse(readFileSync(join(here, 'data', 'legacy_supplications.json'), 'utf8'));
let db;

before(async () => {
  db = await bootDb({ migrations: ['0002_duas_schema.sql', '0003_duas_seed.sql'] });
});

const snapshot = async () => {
  const r = await as(db, 'anon', null, async () => (await db.query('select get_dua_content() j')).rows[0].j);
  return r;
};

test('seed loads every canonical category, dua and mapping', async () => {
  const n = async (t) => (await db.query(`select count(*)::int n from ${t}`)).rows[0].n;
  assert.equal(await n('dua_categories'), canonical.categories.length);
  assert.equal(await n('duas'), canonical.duas.length);
  assert.equal(await n('dua_category_map'), canonical.mappings.length);
});

test('all 106 legacy entries are present as mappings (nothing silently dropped)', async () => {
  const legacyCount = legacy.categories.reduce((s, c) => s + c.duas.length, 0);
  assert.equal(legacyCount, 106);
  const mapped = canonical.mappings.filter((m) => m.legacy_key);
  assert.equal(mapped.length, 106);
  // each legacy (category, index) still resolves, at the same position, in the snapshot
  const snap = await snapshot();
  for (const c of legacy.categories) {
    const cat = snap.categories.find((x) => x.slug === c.id);
    assert.ok(cat, `category ${c.id} present`);
    c.duas.forEach((_, i) => {
      assert.ok(cat.duas.some((d) => d.sort_order === i), `${c.id}#${i} still at legacy position`);
    });
  }
});

test('RPC snapshot equals the bundled fallback snapshot generated by the pipeline', async () => {
  const snap = await snapshot();
  assert.deepEqual(snap.categories, bundled.categories);
});

test('seed is idempotent: re-running changes nothing', async () => {
  const before = await snapshot();
  const { readFileSync: rf } = await import('node:fs');
  const { migrationsDir } = await import('./helpers.mjs');
  await db.exec(rf(join(migrationsDir, '0003_duas_seed.sql'), 'utf8'));
  const after = await snapshot();
  assert.equal(after.version, before.version);
  assert.equal((await db.query('select count(*)::int n from duas')).rows[0].n, canonical.duas.length);
});

test('corrected Duas are complete in the published snapshot', async () => {
  const snap = await snapshot();
  const all = snap.categories.flatMap((c) => c.duas.map((d) => ({ c: c.slug, ...d })));
  const ist = all.find((d) => d.slug.includes('istikharah'));
  assert.match(ist.arabic, /أَرْضِنِي بِهِ$/);
  assert.match(ist.arabic, /فَاقْدُرْهُ لِي/);
  assert.match(ist.arabic, /فَاصْرِفْهُ عَنِّي/);
  const kursi = all.filter((d) => d.slug === 'ayat-al-kursi');
  assert.equal(kursi.length, 2);
  for (const k of kursi) {
    assert.ok(nz(k.arabic).endsWith(nz('وَهُوَ الْعَلِيُّ الْعَظِيمُ')));
    assert.ok(nz(k.arabic).includes(nz('وَسِعَ كُرْسِيُّهُ')));
    assert.deepEqual(k.quran_refs, [{ surah: 2, ayah_from: 255, ayah_to: 255 }]);
  }
  const quls = all.filter((d) => d.slug === 'three-quls');
  assert.equal(quls.length, 2);
  for (const q of quls) {
    assert.equal(q.arabic.split('\n').length, 3);
    assert.ok(nz(q.arabic).endsWith(nz('مِنَ الْجِنَّةِ وَالنَّاسِ')));
    assert.equal(q.repeat_count, 3);
    assert.equal(q.quran_refs.length, 3);
  }
  for (const d of all) assert.ok(!/(\.\.\.|…)\s*$/.test(d.arabic), `${d.slug} arabic must not be truncated`);
});

test('repetition counts are structured, not embedded in titles', async () => {
  const snap = await snapshot();
  const all = snap.categories.flatMap((c) => c.duas);
  for (const d of all) {
    assert.ok(!/\(x\d+\)/i.test(d.title), `${d.slug}: title still has (xN): ${d.title}`);
    assert.ok(!/said \d+ times/i.test(d.title), `${d.slug}: title still has count: ${d.title}`);
  }
  const byKey = (slug, cat) => snap.categories.find((c) => c.slug === cat).duas.find((d) => d.slug === slug);
  assert.equal(snap.categories.find((c) => c.slug === 'morning').duas[0].repeat_count, 1);
  assert.equal(snap.categories.find((c) => c.slug === 'morning').duas[3].repeat_count, 3);
  assert.equal(byKey('three-quls', 'sleep').repeat_count, 3);
});

test('no unexpected duplicate Duas: normalised Arabic is unique across canonical records (except the documented same-category pair)', async () => {
  const seen = new Map();
  const dups = [];
  for (const d of canonical.duas) {
    const k = (await db.query('select normalize_arabic($1) k', [d.arabic])).rows[0].k;
    if (k && seen.has(k)) dups.push([seen.get(k), d.slug]);
    seen.set(k, d.slug);
  }
  assert.deepEqual(
    dups.map((p) => p.join(' = ')),
    ['hajj-atop-safa-and-marwa = hajj-the-best-dua-on-the-day-of-arafah'],
  );
});

test('every published Dua has Arabic, an English translation and a reference', async () => {
  const r = await db.query(`select slug from duas where status='published'
    and (length(btrim(arabic))=0 or length(btrim(translation_en))=0 or length(btrim(coalesce(source_reference,'')))=0)`);
  assert.deepEqual(r.rows, []);
});
