#!/usr/bin/env node
/**
 * Wa Iyyaka Nastaeen (WYN) → Duas sync: the audit-and-approval workflow for content/duas-wyn/catalog.json.
 * Nothing here writes to a real database — it validates, dry-runs, and emits SQL that the owner applies
 * with wrangler (local first, then remote). See content/duas-wyn/README.md.
 *
 *   node scripts/duas-wyn-sync.mjs check
 *   node scripts/duas-wyn-sync.mjs plan [--db <d1.sqlite> | --dump <wrangler-d1-export.sql>] [--with-corrections] [--publish <slugs.txt>]
 *   node scripts/duas-wyn-sync.mjs sql --out <file.sql> [--with-corrections] [--publish <slugs.txt>]
 *
 * `plan` copies the SQLite file (default: the local wrangler D1 under .wrangler/state) — or loads a
 * `wrangler d1 export --remote` dump, to dry-run against production — into memory,
 * applies the SQL there, and reports what would change. It refuses (exit 1) if a published Dua would
 * change without --with-corrections / --publish.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";
import { buildSql, checkCatalog } from "./duas-wyn/sync-lib.mjs";

const root = new URL("../", import.meta.url);
const args = process.argv.slice(2);
const cmd = args[0];
const flag = (n) => args.includes(n);
const opt = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);

const catalog = JSON.parse(readFileSync(new URL("content/duas-wyn/catalog.json", root), "utf8"));
const publishFile = opt("--publish");
const opts = {
  withCorrections: flag("--with-corrections"),
  publish: publishFile
    ? readFileSync(publishFile, "utf8").split(/\r?\n/).map((s) => s.replace(/#.*/, "").trim()).filter(Boolean)
    : undefined,
};

function localD1() {
  const dir = new URL(".wrangler/state/v3/d1/miniflare-D1DatabaseObject/", root);
  if (!existsSync(dir)) return null;
  const f = readdirSync(dir).find((x) => x.endsWith(".sqlite") && x !== "metadata.sqlite");
  return f ? new URL(f, dir) : null;
}

if (cmd === "check") {
  const { errors, warnings } = checkCatalog(catalog);
  const byMode = {};
  for (const d of catalog.duas) byMode[d.mode] = (byMode[d.mode] ?? 0) + 1;
  console.log(`catalog: ${catalog.categories.length} WYN categories, ${catalog.duas.length} Duas ${JSON.stringify(byMode)}, ` +
    `${catalog.placements.length} placements, ${catalog.corrections?.length ?? 0} proposed corrections, ${catalog.exclusions?.length ?? 0} exclusions`);
  for (const w of warnings) console.log(`  warn: ${w}`);
  for (const e of errors) console.log(`  ERROR: ${e}`);
  process.exit(errors.length ? 1 : 0);
} else if (cmd === "sql") {
  const out = opt("--out");
  if (!out) throw new Error("--out <file.sql> is required");
  const stmts = buildSql(catalog, opts);
  writeFileSync(out, `-- Generated by scripts/duas-wyn-sync.mjs from content/duas-wyn/catalog.json (${new Date().toISOString()})\n` +
    `-- corrections: ${opts.withCorrections ? "INCLUDED" : "not included"}; publish: ${opts.publish?.length ?? 0} slug(s)\n` + stmts.join("\n") + "\n");
  console.log(`✓ wrote ${stmts.length} statements to ${out}`);
} else if (cmd === "plan") {
  const dump = opt("--dump");
  const src = dump ?? opt("--db") ?? localD1();
  if (!src) throw new Error("no --db/--dump given and no local D1 found (run `npm run db:migrate:local` first)");
  const db = new DatabaseSync(":memory:");
  if (dump) {
    db.exec(readFileSync(dump, "utf8"));
  } else {
    // Copy the file DB into memory so the source is never written.
    const path = src instanceof URL ? fileURLToPath(src) : src;
    db.exec(`ATTACH DATABASE '${path.replace(/'/g, "''")}' AS src`);
    for (const { name, sql } of db.prepare("SELECT name, sql FROM src.sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' AND name <> 'd1_migrations'").all()) {
      db.exec(sql);
      db.exec(`INSERT INTO main."${name}" SELECT * FROM src."${name}"`);
    }
    db.exec("DETACH DATABASE src");
  }
  db.exec("PRAGMA foreign_keys = ON");
  const snap = () => ({
    duas: new Map(db.prepare("SELECT * FROM duas").all().map((r) => [r.slug, r])),
    cats: new Map(db.prepare("SELECT * FROM dua_categories").all().map((r) => [r.slug, r])),
    maps: new Map(db.prepare("SELECT d.slug ds, c.slug cs, m.sort_order, m.context_repeat_count FROM dua_category_map m JOIN duas d ON d.id = m.dua_id JOIN dua_categories c ON c.id = m.category_id").all().map((r) => [`${r.cs}/${r.ds}`, r])),
  });
  const before = snap();
  for (const s of buildSql(catalog, opts)) db.exec(s);
  const after = snap();
  const ins = [...after.duas.keys()].filter((k) => !before.duas.has(k));
  const changed = [...after.duas].filter(([k, r]) => before.duas.has(k) && JSON.stringify(before.duas.get(k)) !== JSON.stringify(r));
  const pubTouched = changed.filter(([k]) => before.duas.get(k).status === "published");
  const missingReuse = catalog.duas.filter((d) => d.mode !== "insert" && !before.duas.has(d.slug)).map((d) => d.slug);
  const newMaps = [...after.maps.keys()].filter((k) => !before.maps.has(k));
  const movedMaps = [...after.maps].filter(([k, r]) => before.maps.has(k) && JSON.stringify(before.maps.get(k)) !== JSON.stringify(r));
  console.log(`plan against ${src}`);
  console.log(`  categories: ${[...after.cats.keys()].filter((k) => !before.cats.has(k)).length} new, ${[...after.cats].filter(([k, r]) => before.cats.has(k) && JSON.stringify(before.cats.get(k)) !== JSON.stringify(r)).length} updated (rename/reorder)`);
  console.log(`  duas: ${ins.length} inserted as 'review', ${changed.filter(([k]) => before.duas.get(k).status === "draft").length} WYN drafts filled → 'review', ${pubTouched.length} published rows changed`);
  console.log(`  placements: ${newMaps.length} added, ${movedMaps.length} reordered/recounted`);
  const status = db.prepare("SELECT status, count(*) n FROM duas GROUP BY status").all().map((r) => `${r.status}=${r.n}`).join(" ");
  console.log(`  after: ${status}`);
  if (missingReuse.length) console.log(`  ! ${missingReuse.length} catalog Duas expected to exist were not found (their placements are skipped): ${missingReuse.slice(0, 10).join(", ")}`);
  if (pubTouched.length && !opts.withCorrections && !opts.publish?.length) {
    console.error(`✗ published rows would change without approval: ${pubTouched.map(([k]) => k).join(", ")}`);
    process.exit(1);
  }
  for (const [k, r] of pubTouched) {
    const b = before.duas.get(k);
    console.log(`  ~ ${k}: ${Object.keys(r).filter((c) => !["updated_at", "updated_by", "arabic_normalized", "published_at"].includes(c) && r[c] !== b[c]).join(", ")}`);
  }
} else {
  console.log("usage: duas-wyn-sync.mjs check | plan [--db f | --dump f] | sql --out f  [--with-corrections] [--publish slugs.txt]");
  process.exit(cmd ? 1 : 0);
}
